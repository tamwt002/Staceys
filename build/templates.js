// "From the journal" strip on the homepage, filled at build/dev time.
export function renderLatest(posts) {
  if (!posts.length) return '';
  return `<section class="journal" id="journal" aria-labelledby="journal-title">
        <header class="journal__head">
          <p class="eyebrow" data-reveal>From the journal</p>
          <h2 class="journal__title" id="journal-title" data-reveal>Stories from behind the counter</h2>
          <a class="journal__all" href="/blog/" data-reveal>Read the journal <span aria-hidden="true">→</span></a>
        </header>
        <ul class="post-grid post-grid--compact">
          ${posts.map((post, i) => postCard(post, i, { headingLevel: 3 })).join('\n          ')}
        </ul>
      </section>`;
}

// Canonical, Open Graph and local business structured data for the homepage.
export function renderHomeSeo() {
  const business = jsonLd({
    '@context': 'https://schema.org',
    '@type': 'CafeOrCoffeeShop',
    name: site.name,
    url: site.url,
    description: site.description,
    servesCuisine: ['Coffee', 'Brunch'],
    address: {
      '@type': 'PostalAddress',
      addressLocality: site.address.locality,
      addressRegion: site.address.region,
      postalCode: site.address.postcode,
      addressCountry: site.address.country,
    },
    openingHoursSpecification: site.hours.map(({ opens, closes }) => ({
      '@type': 'OpeningHoursSpecification',
      dayOfWeek: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'],
      opens,
      closes,
    })),
  });

  return `<link rel="canonical" href="${abs('/')}" />
    <meta property="og:site_name" content="${escapeHtml(site.name)}" />
    <meta property="og:locale" content="${site.locale}" />
    <meta property="og:type" content="website" />
    <meta property="og:title" content="${escapeHtml(site.name)} · Garden cafe and house parties in Fitzroy" />
    <meta property="og:description" content="${escapeHtml(site.description)}" />
    <meta property="og:url" content="${abs('/')}" />
    <meta property="og:image" content="${abs('/images/hero.jpg')}" />
    <meta name="twitter:card" content="summary_large_image" />
    <link rel="alternate" type="application/rss+xml" title="${escapeHtml(site.name)} Journal" href="/feed.xml" />
    ${business}`;
}

/* ---------- Feeds ---------- */

export function renderSitemap(posts) {
  const latest = posts[0]?.updated ?? posts[0]?.date ?? new Date();
  const urls = [
    { loc: abs('/'), lastmod: latest },
    { loc: abs('/blog/'), lastmod: latest },
    ...posts.map((post) => ({ loc: abs(post.url), lastmod: post.updated ?? post.date })),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${u.lastmod.toISOString().slice(0, 10)}</lastmod></url>`).join('\n')}
</urlset>
`;
}

export function renderFeed(posts) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${escapeHtml(site.name)} Journal</title>
    <link>${abs('/blog/')}</link>
    <description>${escapeHtml(`Stories from ${site.name}, a garden cafe and house party venue in Fitzroy, Melbourne.`)}</description>
    <language>en-au</language>
    <atom:link href="${abs('/feed.xml')}" rel="self" type="application/rss+xml" />
${posts
  .map(
    (post) => `    <item>
      <title>${escapeHtml(post.title)}</title>
      <link>${abs(post.url)}</link>
      <guid>${abs(post.url)}</guid>
      <pubDate>${post.date.toUTCString()}</pubDate>
      <description>${escapeHtml(post.description)}</description>
    </item>`,
  )
  .join('\n')}
  </channel>
</rss>
`;
}

