import site from '../site.config.js';

// HTML templates for the generated blog pages, plus the sitemap, RSS feed
// and the SEO tags injected into the homepage. Pure string functions.

const PLACEHOLDER_COLOURS = ['#a9451a', '#c99a2e', '#5b6436', '#2e3a23'];
const GENERATED_NOTE = 'Generated by build/blog-plugin.js from content/blog. Edit the Markdown, not this file.';

const abs = (path) => new URL(path, site.url).href;

export function escapeHtml(value = '') {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

export const formatDate = (date) =>
  date.toLocaleDateString('en-AU', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Australia/Melbourne' });

const isoDate = (date) => date.toISOString();

const jsonLd = (data) =>
  `<script type="application/ld+json">${JSON.stringify(data).replaceAll('<', '\\u003c')}</script>`;

/* ---------- Shared pieces ---------- */

function head({ title, description, path, type = 'website', image, extra = '' }) {
  const url = abs(path);
  return `<meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(title)}</title>
    <meta name="description" content="${escapeHtml(description)}" />
    <link rel="canonical" href="${url}" />
    <meta name="theme-color" content="#1d2616" />
    <meta property="og:site_name" content="${escapeHtml(site.name)}" />
    <meta property="og:locale" content="${site.locale}" />
    <meta property="og:type" content="${type}" />
    <meta property="og:title" content="${escapeHtml(title)}" />
    <meta property="og:description" content="${escapeHtml(description)}" />
    <meta property="og:url" content="${url}" />
    ${image ? `<meta property="og:image" content="${abs(image)}" />` : ''}
    <meta name="twitter:card" content="${image ? 'summary_large_image' : 'summary'}" />
    <link rel="alternate" type="application/rss+xml" title="${escapeHtml(site.name)} Journal" href="/feed.xml" />
    ${extra}
    <script>
      document.documentElement.classList.add('js');
    </script>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link
      rel="stylesheet"
      href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400..700&family=Fraunces:ital,opsz,wght,SOFT,WONK@0,9..144,400..900,0..100,0..1;1,9..144,400..900,0..100,0..1&display=swap"
    />`;
}

