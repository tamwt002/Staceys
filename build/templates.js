export function postCard(post, index = 0, { headingLevel = 2 } = {}) {
  const h = `h${headingLevel}`;
  return `<li class="post-card">
          <a class="post-card__link" href="${post.url}" data-cursor="read">
            <figure class="slot post-card__img" data-file="blog/${post.slug}.jpg · 16:10" style="--ph: ${PLACEHOLDER_COLOURS[index % PLACEHOLDER_COLOURS.length]}">
              <img src="${post.image}" alt="${escapeHtml(post.imageAlt)}" loading="lazy" width="1200" height="750" />
            </figure>
            <div class="post-card__body">
              <p class="post-card__meta"><time datetime="${isoDate(post.date)}">${formatDate(post.date)}</time> · ${post.readingMinutes} min read</p>
              <${h} class="post-card__title">${escapeHtml(post.title)}</${h}>
              <p class="post-card__excerpt">${escapeHtml(post.description)}</p>
              <span class="post-card__more">Read it <span aria-hidden="true">→</span></span>
            </div>
          </a>
        </li>`;
}

/* ---------- Blog index ---------- */

export function renderIndex(posts) {
  const title = `The Journal · ${site.name}, a cafe in Fitzroy`;
  const description = `Stories, coffee talk and DJ night news from ${site.name}, a garden cafe and house party venue in Fitzroy, Melbourne.`;

  const structured = jsonLd({
    '@context': 'https://schema.org',
    '@type': 'Blog',
    name: `${site.name} Journal`,
    url: abs('/blog/'),
    description,
    publisher: { '@type': 'CafeOrCoffeeShop', name: site.name, url: site.url },
    blogPost: posts.map((post) => ({
      '@type': 'BlogPosting',
      headline: post.title,
      url: abs(post.url),
      datePublished: isoDate(post.date),
    })),
  });

  return `<!doctype html>
<!-- ${GENERATED_NOTE} -->
<html lang="en-AU">
  <head>
    ${head({ title, description, path: '/blog/', extra: structured })}
  </head>
  <body class="page-blog">
    ${nav()}
    <main id="main">
      <header class="journal-head">
        <p class="eyebrow" data-reveal>The Journal</p>
        <h1 class="journal-head__title" data-split>Stories from behind the counter</h1>
        <p class="journal-head__lede" data-reveal>How we started, what's spinning on the decks, and the occasional strong opinion about milk. Written slowly, between shifts.</p>
      </header>
      ${
        posts.length
          ? `<ul class="post-grid">
        ${posts.map((post, i) => postCard(post, i)).join('\n        ')}
      </ul>`
          : '<p class="post-grid__empty">Nothing here yet. The kettle is on.</p>'
      }
    </main>
    ${footer()}
    <script type="module" src="/src/blog.js"></script>
  </body>
</html>
`;
}

/* ---------- Single post ---------- */

export function renderPost(post, posts) {
  // Skip the name suffix when the headline already mentions the cafe.
  const title = post.title.includes(site.name) ? post.title : `${post.title} · ${site.name}`;
  const others = posts.filter((p) => p.slug !== post.slug).slice(0, 2);

  const structured = jsonLd([
    {
      '@context': 'https://schema.org',
      '@type': 'BlogPosting',
      headline: post.title,
      description: post.description,
      image: abs(post.image),
      datePublished: isoDate(post.date),
      dateModified: isoDate(post.updated ?? post.date),
      author: { '@type': 'Person', name: post.author },
      publisher: { '@type': 'Organization', name: site.name, url: site.url },
      mainEntityOfPage: abs(post.url),
      keywords: post.tags.join(', '),
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: abs('/') },
        { '@type': 'ListItem', position: 2, name: 'Journal', item: abs('/blog/') },
        { '@type': 'ListItem', position: 3, name: post.title, item: abs(post.url) },
      ],
    },
  ]);

  const articleMeta = `<meta property="article:published_time" content="${isoDate(post.date)}" />
    ${post.tags.map((tag) => `<meta property="article:tag" content="${escapeHtml(tag)}" />`).join('\n    ')}
    ${structured}`;

  return `<!doctype html>
<!-- ${GENERATED_NOTE} -->
<html lang="en-AU">
  <head>
    ${head({ title, description: post.description, path: post.url, type: 'article', image: post.image, extra: articleMeta })}
  </head>
  <body class="page-blog page-post">
    ${nav()}
    <div class="read-progress" aria-hidden="true"><span></span></div>
    <main id="main">
      <article class="post">
        <header class="post__head">
          <nav class="crumbs" aria-label="Breadcrumb">
            <ol>
              <li><a href="/">Home</a></li>
              <li><a href="/blog/">Journal</a></li>
            </ol>
          </nav>
          <p class="post__meta"><time datetime="${isoDate(post.date)}">${formatDate(post.date)}</time> · ${post.readingMinutes} min read</p>
          <h1 class="post__title" data-split>${escapeHtml(post.title)}</h1>
          <p class="post__lede" data-reveal>${escapeHtml(post.description)}</p>
          <p class="post__byline" data-reveal>Words by ${escapeHtml(post.author)}</p>
        </header>

        <figure class="slot post__cover" data-file="blog/${post.slug}.jpg · 16:9" style="--ph: #a9451a">
          <img src="${post.image}" alt="${escapeHtml(post.imageAlt)}" width="1600" height="900" fetchpriority="high" />
        </figure>

        <div class="prose">
${post.html}
        </div>

        <footer class="post__foot">
          ${post.tags.length ? `<ul class="post__tags" aria-label="Tags">${post.tags.map((tag) => `<li>${escapeHtml(tag)}</li>`).join('')}</ul>` : ''}
          <div class="post__cta">
            <p>Reading about it is nice. Tasting it is better.</p>
            <a class="btn btn--rust" href="/#visit">Come say hi</a>
          </div>
        </footer>
      </article>

      ${
        others.length
          ? `<section class="more" aria-labelledby="more-title">
        <h2 class="more__title" id="more-title">More from the journal</h2>
        <ul class="post-grid post-grid--compact">
          ${others.map((p, i) => postCard(p, i + 1, { headingLevel: 3 })).join('\n          ')}
        </ul>
      </section>`
          : ''
      }
    </main>
    ${footer()}
    <script type="module" src="/src/blog.js"></script>
  </body>
</html>
`;
}

